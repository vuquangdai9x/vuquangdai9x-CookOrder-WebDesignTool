// Customer Config for the node graph — the LEGACY page, with graph rules under it.
//
// The layout, the class names and the element sizes are a 1-1 copy of
// design/customerSection.ts: the same `.level-params-bar`, the same estimate
// bar and chart foldout, the same `.customer-cards` row with Sortable
// reordering and a trailing add-card, the same `.customer-head` with its wait
// badge and weather toggle, and the same `.dish-row` / `.dish-chips` /
// `.chip icon-chip dish-chip` at 64px. A designer moving between the two tabs
// should not be able to tell them apart by looking.
//
// What changes is underneath, and it shows up in exactly one place a designer
// can see: RIGHT-CLICKING A DISH opens a menu that configures that dish's
// nested composite and groups. A legacy dish is a flat bag of cooked ids, so
// its dish menu had nothing structural to offer; a node dish is a bracket tree,
// so that menu is where the tree is edited.
//
// The chips themselves stay flat, in resolved slot order (base first). Chip
// gestures are the legacy ones, narrowed to what the graph allows: `＋` offers
// options grouped by slot, and right-clicking a chip swaps it within its own
// slot rather than across every cooked ingredient in the map.

